"""Push the generated HermitLM training/eval data to Hugging Face Hub.

Requires a write-enabled token via HF_TOKEN or `hf auth login`.
"""
import argparse
import os
import sys

from dotenv import load_dotenv

load_dotenv()

DATASET_CARD = """---
license: mit
language: en
tags:
- crab-chat
- synthetic-data
- hermitlm
---

# hermitlm-100k-generic

Synthetic crab-persona chat data used to train `darshi1337/hermitlm-8M`.

## Splits

- `train.jsonl` / `eval.jsonl`: 95,000 / 5,000 persona chat examples with fields
  `input`, `output`, `type`. Generated by `hermitlm.training.generate_data`.
- `train_openai.jsonl` / `eval_openai.jsonl`: the same rows in chat format
  (`messages` with `user`/`assistant` roles).
- `tool_train.jsonl` / `tool_eval.jsonl`: 5,038 / 80 tool-routing examples with
  fields `input`, `label` in {math, web, faq, chat}. Eval queries are disjoint
  from train.
- `human_eval.jsonl`: 126 hand-written intent queries (6 per fine type), the
  held-out set used to measure the real paraphrase gap.
- `tokenizer.json`: byte-level BPE tokenizer used by the matching model repo.

A fraction of the user turns are prefixed with `[hungry crab]`, `[guard crab]`,
or `[sleepy crab]` to teach the model the inference-time persona markers.

## Use

```python
from datasets import load_dataset
ds = load_dataset("darshi1337/hermitlm-100k-generic", data_files="train.jsonl")
```
"""


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--repo", default="darshi1337/hermitlm-100k-generic")
    p.add_argument("--data-dir", default="data")
    p.add_argument("--private", action="store_true")
    p.add_argument("--commit-message", default="Upload retrained HermitLM dataset")
    p.add_argument("--dry-run", action="store_true")
    a = p.parse_args()

    names = [
        "train.jsonl",
        "eval.jsonl",
        "train_openai.jsonl",
        "eval_openai.jsonl",
        "tool_train.jsonl",
        "tool_eval.jsonl",
        "human_eval.jsonl",
        "tokenizer.json",
    ]
    files = [os.path.join(a.data_dir, name) for name in names]
    missing = [f for f in files if not os.path.isfile(f)]
    if missing:
        print("Missing files:", ", ".join(missing))
        sys.exit(1)

    if a.dry_run:
        print("Dry run OK. Files ready:")
        for f in files:
            print(f"  {f} ({os.path.getsize(f)} bytes)")
        print("  <generated> -> README.md (dataset card)")
        return

    from huggingface_hub import HfApi

    api = HfApi(token=os.environ.get("HF_TOKEN"))
    api.create_repo(a.repo, exist_ok=True, private=a.private, repo_type="dataset")
    for src, dest in zip(files, names):
        api.upload_file(
            path_or_fileobj=src,
            path_in_repo=dest,
            repo_id=a.repo,
            repo_type="dataset",
            commit_message=a.commit_message,
        )
    api.upload_file(
        path_or_fileobj=DATASET_CARD.encode(),
        path_in_repo="README.md",
        repo_id=a.repo,
        repo_type="dataset",
        commit_message=a.commit_message,
    )
    print(f"Pushed to {a.repo}")


if __name__ == "__main__":
    main()
